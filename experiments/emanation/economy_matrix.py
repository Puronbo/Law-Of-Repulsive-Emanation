G0 = P.g0                      # 0.05 (base draw at depth 0)


def fresh(depth):
    """Fresh accounts with buyer pre-positioned (credit<0) to set depth d."""
    c = Commons(P)
    b = c.add_account(seed_credit=0.0, seed_trust=10.0)
    s = c.add_account(seed_credit=0.0, seed_trust=10.0)
    if depth > 0:
        c.accounts[b].credit = -depth * 10.0
    return c, b, s


def pair_trust_deltas(X, depth):
    c, b, s = fresh(depth)
    t0 = (c.accounts[b].trust, c.accounts[s].trust)
    c.trade(b, s, X, necessity=False, terminal=s)
    t1 = (c.accounts[b].trust, c.accounts[s].trust)
    return t1[0] - t0[0], t1[1] - t0[1]


def measure_matrix(X0=1.0, step_d=0.1):
    """Two-point finite differences, mirroring Ch.86's measured matrix."""
    t0_0, t0_s = pair_trust_deltas(0.0, 0.0)     # origin: both = 0
    tx_0, tx_s = pair_trust_deltas(X0, 0.0)      # X sweep (c geodesic)
    t0_d, t0_sd = pair_trust_deltas(X0, step_d)  # depth sweep at fixed X

    R11 = (tx_0 - t0_0) / X0        # d(T_buyer)/dX   ~ -g0
    R21 = (tx_s - t0_s) / X0        # d(T_seller)/dX  ~ +reward
    R12 = (t0_d - tx_0) / step_d    # d(T_buyer)/dd   ~ -g0*gdepth
    R22 = (t0_sd - tx_s) / step_d   # d(T_seller)/dd  ~ 0
    return {"R11": R11, "R12": R12, "R21": R21, "R22": R22}


