def L_value_negative_int(n, chi_values):
    """
    L(1-n, chi) = -B_{n,chi} / n for n >= 1.
    """
    if n <= 0:
        return Fraction(0)
    Bn_chi = generalized_bernoulli(chi_values, n)
    return -Bn_chi[n] / Fraction(n)


def kubota_leopoldt_value(n, p, chi_values):
    """
    Kubota-Leopoldt p-adic L-value:
    L_p(1-n, chi) = (1 - chi(p) * p^{n-1}) * L(1-n, chi)
    for n >= 1.

    For the trivial character chi = 1:
    L_p(1-n) = (1 - p^{n-1}) * (1 - n) * zeta(1-n)
    and zeta(1-n) = -B_n / n.
    """
    f = len(chi_values)
    chi_p = chi_values[p % f] if p % f < f else Fraction(0)
    euler_factor = Fraction(1) - chi_p * Fraction(p) ** (n - 1)
    Lv = L_value_negative_int(n, chi_values)
    return euler_factor * Lv


