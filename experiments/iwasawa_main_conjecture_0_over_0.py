# Bernoulli numbers (exact rational arithmetic)
# ---------------------------------------------------------------------------

def bernoulli_numbers_up_to(N):
    """
    Compute B_0, B_1, ..., B_N using the recursive definition.
    B_0 = 1, and for m >= 1:
        sum_{k=0}^{m} binom(m+1, k) * B_k = 0
    So B_m = -1/(m+1) * sum_{k=0}^{m-1} binom(m+1, k) * B_k
    """
    B = [Fraction(0)] * (N + 1)
    B[0] = Fraction(1)

    for m in range(1, N + 1):
        s = Fraction(0)
        for k in range(m):
            # binom(m+1, k)
            c = Fraction(1)
            for j in range(1, k + 1):
                c *= Fraction(m + 1 - j + 1, j)
            s += c * B[k]
        B[m] = -s / Fraction(m + 1)

    return B


def generalized_bernoulli(chi_values, N):
    """
    Compute generalized Bernoulli numbers B_{n, chi} for n = 0, ..., N.

    chi_values: list of chi(a) for a = 0, 1, ..., f-1 (mod f)
    where f = len(chi_values) is the conductor.

    The generalized Bernoulli numbers satisfy:
        sum_{n=0}^{inf} B_{n,chi} * t^n / n! =
            sum_{a=1}^{f} chi(a) * t * e^{at} / (e^{ft} - 1)

    We compute using the recurrence:
        B_{n,chi} = f^{n-1} * sum_{a=0}^{f-1} chi(a) * B_n(a/f)
    where B_n(x) is the nth Bernoulli polynomial.
    """
    f = len(chi_values)
    B = bernoulli_numbers_up_to(N + 2)

    # Bernoulli polynomials via: B_n(x) = sum_{k=0}^{n} binom(n,k) B_k x^{n-k}
    def bernoulli_poly(n, x):
        """Evaluate B_n(x) as a Fraction."""
        result = Fraction(0)
        for k in range(n + 1):
            # binom(n, k)
            c = Fraction(1)
            for j in range(1, k + 1):
                c *= Fraction(n - j + 1, j)
            result += c * B[k] * Fraction(x) ** (n - k)
        return result

    result = []
    for n in range(N + 1):
        s = Fraction(0)
        for a in range(f):
            chi_a = Fraction(chi_values[a])
            if chi_a == 0:
                continue
            bn_a = bernoulli_poly(n, Fraction(a, f))
            s += chi_a * bn_a
        # B_{n,chi} = f^{n-1} * s (for n >= 1)
        if n == 0:
            result.append(s)
        else:
            result.append(Fraction(f) ** (n - 1) * s)

    return result


