    # Over the cyclotomic Z_p-extension of Q
    # For p=5: the characteristic ideal is (L_p(E, 1))

    # Verify: the BSD formula holds
    bsd_holds = abs(lhs - rhs) < 0.01

    # The 0/0 structure:
    # At rank 0: L(E,1) != 0, Sha finite -> BSD is a finite ratio
    # At rank >= 1: L(E,1) = 0, Sha may be infinite -> 0/0
    # The removable value at rank 0 = the BSD formula
    rank_0_test = {
        'rank': rank,
        'L_E_1': L_E_1,
        'Omega': Omega,
        'L_over_Omega': lhs,
        'Sha': Sha,
        'c_2': c_2,
        'torsion_order': torsion_order,
        'rhs': rhs,
        'bsd_ratio': lhs / rhs if rhs > 0 else 0,
        'bsd_holds': bsd_holds,
    }

    # Additional curve: y^2 = x^3 + x (rank 0, conductor 64)
    Omega2 = 2.622057554292119810464839589  # same real period by symmetry
