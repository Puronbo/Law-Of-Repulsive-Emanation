    rhs = 1 * Sha * c_2 / (torsion_order ** 2)

    # The p-adic version: L_p(E, 1)
    # For the p-adic L-function, we use the interpolation:
    # L_p(E, 1-n) = (1 - a_p * p^{n-1} + p^{2n-2}) * L(E, 1-n) / Omega
